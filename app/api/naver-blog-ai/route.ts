export async function POST(request: Request) {
  try {
    const formData = await request.formData();

    const branch = String(formData.get("branch") || "목동점");
    const keyword = String(formData.get("keyword") || "");
    const topic = String(formData.get("topic") || "복싱 입문");
    const memo = String(formData.get("memo") || "");

    if (!keyword) {
      return Response.json(
        { ok: false, message: "키워드를 입력해주세요." },
        { status: 400 }
      );
    }

    const files = formData.getAll("files") as File[];
    const limitedFiles = files.slice(0, 12);

    const imageInputs: any[] = [];

    for (const file of limitedFiles) {
      const buffer = Buffer.from(await file.arrayBuffer());

      const resized = await sharp(buffer)
        .resize(900)
        .jpeg({ quality: 70 })
        .toBuffer();

      imageInputs.push({
        type: "input_image",
        image_url: `data:${file.type};base64,${resized.toString("base64")}`,
      });
    }

    const info = branchInfo[branch] || branchInfo["목동점"];

    const response = await client.responses.create({
      model: "gpt-4.1-mini",
      instructions: SYSTEM_PROMPT,
      input: [
        {
          role: "user",
          content: [
            {
              type: "input_text",
              text: `아래 정보로 네이버 블로그 글을 작성해줘.

지점: ${branch}
지역: ${info.area} (지역 키워드: ${info.regions.join(", ")})
운영시간: ${info.hours}
핵심 키워드: ${keyword}
글 주제: ${topic}
추가 메모: ${memo || "없음"}
SEO 키워드 참고: ${info.keywords.join(", ")}

${branch === "철산점" ? "※ 철산점은 현재 정상 운영 중이므로 오픈 예정, 오픈 준비 중, 곧 오픈 같은 표현은 절대 쓰지 않습니다." : ""}

반드시 JSON만 출력해. 설명 텍스트 없이 JSON만.`,
            },
            ...imageInputs,
          ],
        },
      ],
    });

    const text = response.output_text.trim();
    const clean = text.startsWith("```")
      ? text.replace(/^```(?:json)?\n?/, "").replace(/\n?```$/, "")
      : text;
    const json = JSON.parse(clean);

    return Response.json({
      ok: true,
      draft: json,
    });
  } catch (error) {
    console.error("네이버 블로그 AI 오류:", error);

    return Response.json(
      { ok: false, message: "네이버 블로그 AI 생성 실패" },
      { status: 500 }
    );
  }
}
